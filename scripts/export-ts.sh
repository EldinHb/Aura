#!/usr/bin/env bash
# Export Rust types to TypeScript (ts-rs) into apps/desktop/src/gen.
set -euo pipefail
cd "$(dirname "$0")/.."
# Keep build output out of Spotlight: target/ holds real .app bundles, and an
# indexed copy shows up in Spotlight/Launch Services alongside the installed
# app. cargo clean removes the marker, so re-create it on every build.
mkdir -p target && touch target/.metadata_never_index
OUT="$PWD/apps/desktop/src/gen"
rm -rf "$OUT"; mkdir -p "$OUT"
TS_RS_EXPORT_DIR="$OUT" cargo test -p aura-core -p aura-rpc -p aura-git export_bindings -q >/dev/null
# JSON numbers are plain numbers on the wire; ts-rs emits bigint for u64/i64.
sed -i.bak "s/bigint/number/g" "$OUT"/*.ts && rm -f "$OUT"/*.bak
# index file
{
  echo "// Generated by scripts/export-ts.sh — do not edit."
  for f in "$OUT"/*.ts; do
    n=$(basename "$f" .ts)
    [ "$n" = "index" ] && continue
    echo "export * from './$n';"
  done
} > "$OUT/index.ts"
echo "exported $(ls "$OUT" | wc -l | tr -d ' ') files to $OUT"
